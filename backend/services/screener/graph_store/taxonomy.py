"""Skill taxonomy: canonical skill names and their aliases.

Loaded from skill_taxonomy.json (generated by scripts/seed_taxonomy.py, then
curated by hand). Used to find skills in job offers and resumes, and to give
the experience scorer the words that make a position job-relevant.
"""
import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from services.screener.scoring.normalize import fold, term_pattern

TAXONOMY_PATH = Path(__file__).with_name("skill_taxonomy.json")


@dataclass(frozen=True)
class Skill:
    name: str
    aliases: tuple[str, ...]
    category: str
    related: tuple[str, ...] = ()


class SkillTaxonomy:
    def __init__(self, skills: list[Skill]):
        self.skills = {s.name: s for s in skills}
        self._by_alias: dict[str, str] = {}
        for skill in skills:
            for term in (skill.name, *skill.aliases):
                self._by_alias.setdefault(fold(term).strip(), skill.name)
        # Only aliases are matched in free text: some names ("r") are too short
        self._pattern = term_pattern([a for s in skills for a in s.aliases])

    @classmethod
    def load(cls, path: Path = TAXONOMY_PATH) -> "SkillTaxonomy":
        raw = json.loads(Path(path).read_text(encoding="utf-8"))
        return cls([
            Skill(
                name=item["name"],
                aliases=tuple(item.get("aliases", [])),
                category=item.get("category", "other"),
                related=tuple(item.get("related", [])),
            )
            for item in raw["skills"]
        ])

    def canonical(self, term: str) -> str | None:
        """Canonical name for a skill name or alias, or None if unknown."""
        return self._by_alias.get(fold(term).strip())

    def find_skills(self, text: str) -> set[str]:
        """Canonical names of every skill mentioned in the text."""
        if self._pattern is None or not text:
            return set()
        return {self._by_alias[m.group(0)] for m in self._pattern.finditer(fold(text))}

    def terms_for(self, names: set[str]) -> set[str]:
        """All aliases of the given skills, for matching them in resume text."""
        return {alias for name in names for alias in self.skills[name].aliases}


@lru_cache(maxsize=1)
def default_taxonomy() -> SkillTaxonomy:
    return SkillTaxonomy.load()
